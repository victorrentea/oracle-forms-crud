-- Schema for the Orders "form": two business tables + an audit trail.
-- Re-runnable: drops everything first.

begin
  for t in (select table_name from user_tables
            where table_name in ('AUDIT_LOG', 'ORDERS', 'CUSTOMERS')) loop
    execute immediate 'drop table ' || t.table_name || ' cascade constraints purge';
  end loop;
end;
/

create table customers (
  id            number generated by default as identity primary key,
  name          varchar2(100) not null,
  credit_limit  number(12,2)  not null,
  active        char(1)       default 'Y' not null,
  constraint customers_name_uk unique (name),
  constraint customers_active_ck check (active in ('Y', 'N')),
  constraint customers_credit_ck check (credit_limit >= 0)
);

create table orders (
  id            number generated by default as identity primary key,
  customer_id   number        not null references customers (id),
  product       varchar2(100) not null,
  quantity      number(6)     not null,
  unit_price    number(10,2)  not null,
  discount_pct  number(5,2)   default 0 not null,  -- derived by trigger
  total         number(12,2)  not null,            -- derived by trigger
  status        varchar2(10)  default 'NEW' not null,
  created_at    date          default sysdate not null,
  updated_at    date,
  constraint orders_status_ck check (status in ('NEW', 'SHIPPED', 'CANCELLED'))
);

create table audit_log (
  id          number generated by default as identity primary key,
  table_name  varchar2(30)   not null,
  row_id      number         not null,
  action      varchar2(10)   not null,
  old_values  varchar2(4000),
  new_values  varchar2(4000),
  changed_at  date           default sysdate not null,
  changed_by  varchar2(128)  default user not null
);

create or replace view v_orders as
select o.id, o.customer_id, c.name customer_name, o.product, o.quantity,
       o.unit_price, o.discount_pct, o.total, o.status, o.created_at, o.updated_at
  from orders o
  join customers c on c.id = o.customer_id;
